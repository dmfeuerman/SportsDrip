/**
 * Secondary (trim) colours for the big-four leagues, keyed `${sport}:${abbr}`.
 * Colours are facts, not artwork: they let a crest read as the team without
 * any league or club logo. Used when the games feed carries no alternate
 * colour (favourite-team chips, bet tickets, challenges).
 */
const rows = (sport: string, s: string): Array<[string, string]> =>
  s.trim().split(/\s+/).map((pair) => {
    const [abbr, hex] = pair.split("=");
    return [`${sport}:${abbr}`, `#${hex}`];
  });

