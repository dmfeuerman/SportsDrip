#!/usr/bin/env node
/**
 * Writes lib/avatar3d/assetRegistry.generated.ts from assets/avatar/*.glb.
 *
 * Metro only bundles assets it can see as static `require()` calls, so the
 * registry has to be code. Every GLB is validated first; an invalid one is
 * left out (and the script exits non-zero) rather than shipped.
 *
 * Kinds: the base character, garment templates, and appearance parts
 * (hair_<style>, beard_<style>) that load one at a time for the current look.
 *
 *   node scripts/avatar/registry.mjs
 */
import { readdirSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { assetDir, validateGlb } from "./validate.mjs";

const dir = assetDir();
const files = readdirSync(dir).filter((f) => f.endsWith(".glb")).sort();
const entries = [];
let failed = 0;
for (const f of files) {
  const r = validateGlb(join(dir, f));
  if (!r.ok) {
    failed++;
    console.error(`skipping ${f}: ${r.errors.join("; ")}`);
    continue;
  }
  const key = basename(f, ".glb");
  const m = r.meta;
  entries.push(
    `  ${JSON.stringify(key)}: {\n` +
      `    module: require("@/assets/avatar/${f}"),\n` +
      `    kind: ${JSON.stringify(m.kind)},\n` +
      `    version: ${m.version},\n` +
      (m.kind === "garment"
        ? `    slot: ${JSON.stringify(m.slot)},\n    hairMode: ${JSON.stringify(m.hairMode ?? null)},\n    excludes: ${JSON.stringify(m.excludes ?? [])},\n`
        : "") +
      `    bytes: ${r.bytes},\n  },`
  );
}

const out = `// GENERATED by scripts/avatar/registry.mjs — do not edit by hand.
// Re-run after adding, removing or regenerating anything in assets/avatar/.
/* eslint-disable */
import type { AvatarAssetEntry } from "./spec";

export const AVATAR_ASSETS: Record<string, AvatarAssetEntry> = {
${entries.join("\n")}
};
`;
writeFileSync(join(dir, "..", "..", "lib", "avatar3d", "assetRegistry.generated.ts"), out);
console.log(`registry: ${entries.length} assets${failed ? `, ${failed} skipped` : ""}`);
process.exit(failed ? 1 : 0);
