/**
 * Renders every catalog item (scripts/catalog-data.mjs) to a store icon with the
 * same rig, lights and framing as the in-app portrait studio, then writes
 * assets/items/<id>.webp and lib/avatar3d/itemThumbs.generated.ts.
 *
 *   cd artifacts/mobile
 *   npm i --no-save esbuild playwright && npx playwright install chromium
 *   node scripts/item-thumbs/render.cjs
 *
 * Re-run after adding items or changing an item's model/colours.
 */
const path = require("path");
const fs = require("fs");
const http = require("http");
const esbuild = require("esbuild");
const { chromium } = require("playwright");

const mobile = path.resolve(__dirname, "../..");
const here = __dirname;

(async () => {
  const bundle = (await esbuild.build({
    entryPoints: [path.join(here, "entry.ts")],
    bundle: true,
    format: "esm",
    write: false,
    logLevel: "warning",
    alias: { "@/types": path.join(mobile, "types"), "@/lib": path.join(mobile, "lib") },
  })).outputFiles[0].text;

  const server = http.createServer((req, res) => {
    if (req.url === "/") return res.end('<!doctype html><body style="margin:0"><script type="module" src="/bundle.js"></script>');
    if (req.url === "/bundle.js") return res.writeHead(200, { "content-type": "text/javascript" }), res.end(bundle);
    const file = path.join(mobile, decodeURIComponent(req.url.split("?")[0]));
    if (!file.startsWith(path.join(mobile, "assets")) || !fs.existsSync(file)) return res.writeHead(404), res.end();
    res.end(fs.readFileSync(file));
  });
  await new Promise((r) => server.listen(0, r));
  const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
  const page = await browser.newPage();
  page.on("pageerror", (e) => console.error("[page]", e.message));
  await page.goto(`http://localhost:${server.address().port}/`);
  await page.waitForFunction("window.ready === true", null, { timeout: 60000 });
  const { res, errors } = await page.evaluate(() => window.renderAll());
  await browser.close();
  server.close();

  const dir = path.join(mobile, "assets/items");
  fs.mkdirSync(dir, { recursive: true });
  const seen = new Set();
  const lines = [];
  for (const x of res.sort((a, b) => a.id.localeCompare(b.id))) {
    fs.writeFileSync(path.join(dir, `${x.id}.webp`), Buffer.from(x.data.split(",")[1], "base64"));
    if (seen.has(x.key)) continue;
    seen.add(x.key);
    lines.push(`  "${x.key}": require("@/assets/items/${x.id}.webp"),`);
  }
  fs.writeFileSync(
    path.join(mobile, "lib/avatar3d/itemThumbs.generated.ts"),
    `// GENERATED by scripts/item-thumbs/render.cjs — do not edit by hand.
// Pre-rendered store icons, keyed like the live item portrait (pieceLook: template, colours, pattern, metal),
// so an item whose look changes in the database misses here and falls back to the live render.
/* eslint-disable */
export const ITEM_THUMBS: Record<string, number> = {
${lines.join("\n")}
};

/** The same icons by item id: a stand-in while a changed item's live render is on its way. */
export const ITEM_THUMBS_BY_ID: Record<string, number> = {
${res.map((x) => `  "${x.id}": require("@/assets/items/${x.id}.webp"),`).join("\n")}
};
`
  );
  console.log(`rendered ${res.length} items`);
  if (errors.length) console.warn("skipped:", errors);
})();
